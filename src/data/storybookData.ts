export type VocabCategory = 'Fruit' | 'Food' | 'Drink';

export interface VocabularyWord {
  id: string;
  word: string;
  category: VocabCategory;
  phonetic: string;
  syllables: string[];
  definition: string;
  exampleSentence: string;
  funFact: string;
  colorAccent: string;
}

export interface TextSegment {
  text: string;
  vocabId?: string;
}

export interface InteractiveProp {
  id: string;
  label: string;
  actionText: string;
  speechPhrase: string;
  soundType: 'pop' | 'splash' | 'crunch';
  xPercent: number;
  yPercent: number;
  iconType: string;
}

export interface ComprehensionCheck {
  question: string;
  options: string[];
  correctIndex: number;
  encouragement: string;
}

export interface WordPuzzleItem {
  vocabId: string;
  displayPattern: string[];
  missingIndices: number[];
  missingLetters: string[];
  distractorLetters: string[];
  hint: string;
}

export interface StoryPage {
  pageNumber: number; // 1 to 20
  chapterNumber: number; // 1 to 4
  chapterTitle: string;
  pageType: 'story' | 'game';
  title: string;
  illustrationUrl: string;
  sceneTheme: string;
  interactivePrompt: string;
  segments?: TextSegment[];
  plainNarrationText: string;
  interactiveProps?: InteractiveProp[];
  comprehensionCheck?: ComprehensionCheck;
  gamePuzzles?: WordPuzzleItem[];
}

